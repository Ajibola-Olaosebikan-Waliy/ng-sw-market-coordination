@task(
    name = "validate-wfp-nigeria",
    retries = 3,
    retry_delay_seconds = 15,
    description = (
        "Validates the messy WFP Nigeria CSV data for maize, rice and millet."
        "Run pandera schema and check out the business logic successfully."
        "Save JSON quality report to data/quality_reports/."
    ),
)
def validate_data(raw_path: Path) -> pd.DataFrame:
    """
    The main data validation function that serves as the public entry point 
    for the validate.py module or file. It takes the path to the CSV file
    produced in extract.py module and validates it before returning it as 
    a pandas data-frame to used by the transform.py module. 
    """
    try:
        logger = get_run_logger()
    except Exception:
        logger = logging.getLogger("src.pipeline.validate")
    logger.info("== Data Loading started==")
    logger.info(f"Input file: {raw_path}")

    ## Stage 1: Load the extracted CSV file ##
    data_frame = pd.read_csv(raw_path)
    logger.info(
        f"Loaded {len(data_frame):,} rows"
        f"{len(data_frame.columns)} columns"
    )

    ## Stage 2: Pandera schema validation ##
    schema = _build_schema()
    schema_passed = True
    schema_errors = []

    try:
        schema.validate(data_frame, lazy=True)
        logger.info("Schema validation: Passed")

    except pa.errors.SchemaErrors as exc:
        schema_passed = False
        schema_errors = (
            exc.failure_cases["failure_case"]
            .astype(str)
            .unique()
            .tolist()
        )
        logger.warning(
            f"Schema validation: FAILED - "
            f"{len(schema_errors)} issue(s) found"
        )
        for an_error in schema_errors[:5]:
            logger.warning(f" -> {an_error}")
    
    ## Build the data quality report ##
    report = _generate_data_quality_report(data_frame,schema_passed,schema_errors)
    all_passed = report["summary"]["all_checks_passed"]

    ## Save the qualtiy report to disk ##
    report_path = _path_report_timestamped()
    with open(report_path, "w", encoding="utf-8") as data_file:
        json.dump(report, data_file, indent=2, default=str)
    logger.info(f"Quality report saved -> {report_path.name}")

    ## Log the report summary ##
    logger.info("===Summary of validation===")
    logger.info(
        f" Rows checked : {report['summary']['total_rows']:,}"
    )
    logger.info(
        f" Schema passed : {schema_passed}"
    )
    logger.info(
        f" Markets present :"
        f"{report['business_rule_checks']['present_markets']}"
    )
    logger.info(
        f" Date range :"
        f"{report['business_rule_checks']['duplicate_records']}"
    )
    logger.info(
        f" Duplicates found: "
        f"{report['business_rule_checks']['date_range_years']}"
    )
    logger.info(f" All checks passed: {all_passed}")

    checks = report["business_rule_checks"]

    if not checks["markets_check"]:
        raise ValueError(
            f"Critical: missing markets in data - "
            f"{checks['missing_markets']}. "
            f"Check TARGET_MARKETS in config.py."
        )
    if not checks["commodities_check"]:
        raise ValueError(
            f"Critical: missing commodities in data - "
            f"{checks['commodities_missing']}. "
            f"Check TARGET_COMMODITIES in config.py."
        )
    if not checks["date_range_check"]:
        raise ValueError(
            f"Critical: date range too sort -"
            f"{checks['date_range_years']} years."
            f"Need at least 5 years of data for forecasting."
        )
    logger.info("=== Completed data validation ===")

    if not checks["duplicate_check"]:
        logger.warning(
        f"Warning: {checks['duplicate_records']} duplicate "
        f"records found. These will be handled in transform.py."
    )

    return data_frame


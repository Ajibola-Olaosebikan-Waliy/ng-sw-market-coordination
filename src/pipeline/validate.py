def _create_dir(path: Path) -> Path:
    """Create directory if it does not exist at path,
    and return the path.
    """
    path.mkdir(parents=True, exist_ok=True)
    return path

def _path_report_timestamped() -> Path:
    """This generates a unique time-stamped data quality report per execution
    it gives a complete audit trail of data quality over time"""
    
    time_stamped = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    file_name = f"data_quality_report_{time_stamped}.json"
    return _create_dir(QUALITY_DIR) / file_name 


def _build_schema() -> DataFrameSchema:
    """It builds and return the pandera validated DataFrameSchema for
    the extracted CSV data. It ensures data is successfully screened for
    modelling purpose"""

    return DataFrameSchema(
        columns={"date": Column(
            pa.String, nullable=False,description="Price observation date(YYYY-MM-DD)"
        ),

        "admin1": Column(
            pa.String, nullable=False, description="State name"
        ),
        "admin2": Column(
            pa.String, nullable=False,description="LGA or city name"
        ),
        "market": Column(
            pa.String, Check.isin(TARGET_MARKETS),
            nullable=False,
            description="Market name - must match TARGET_MARKETS"
        ),
        "market_id": Column(
            pa.Int, nullable=False,description="Numeric marekt identifier"
        ),
        "latitude": Column(
            pa.Float, Check.in_range(-90,90),nullable=False,description="Market GPS latitude"
        ),
        "longitude": Column(
            pa.Float, Check.in_range(-180, 180),nullable=False,description="Market GPS longitude"
        ),"category": Column(
            pa.String, Check.isin([TARGET_CATEGORY]),nullable=False,description="Food category"
        ),
        "commodity": Column(
            pa.String, Check.isin(TARGET_COMMODITIES),nullable=False,
            description="Commodity name: must match TARGET_COMMODITIES"
        ),
        "commodity_id": Column(
            pa.Int, nullable=False,description="Numeric commodity identifier"
        ),
        "unit": Column(
            pa.String, Check.isin(["100 KG", "50 KG", "KG", "2.6 KG", "2.8 KG"]), nullable=False,description="Unit of measurement per 100 kg"
        ),
        "priceflag": Column(
            pa.String, nullable=False,description="Data quality flag"
        ),
        "pricetype": Column(
            pa.String, Check.isin(["Wholesale", "Retail"]),nullable=False,description="Price type"
        ),
        "currency": Column(
            pa.String, Check.isin(["NGN"]),nullable=False,description="Currency in NGN for Nigeria"
        ),
        "price": Column(
            pa.Float, Check.greater_than(0),nullable=False,description="Price in NGN must be positive"
        ),
        "usdprice": Column(
            pa.Float, Check.greater_than(0),nullable=True,description="Comparable price in USD: nullable for historical gaps"

        ),

        },
    )

def _generate_data_quality_report(df: pd.DataFrame, schema_passed:bool, schema_errors: list) -> dict:
    """This function generates the data quality reports from the pandera
    validated DataFrame. he report is stored in a dictionary. The report has three sections:
    1. Summary of the dataframe (rows, and column counts, fail or pass status)
    2. A checklist of each business rule
    3. The statistics of the numerical variable columns"""

    present_markets = sorted(df["market"].unique().tolist())
    present_commodities = sorted(df["commodity"].unique().tolist())
    missing_markets = sorted(set(TARGET_MARKETS)-set(present_markets))
    missing_commodities = sorted(set(TARGET_COMMODITIES) - set(present_commodities))

    ## Range of Date ###
    df["date"] = pd.to_datetime(df["date"])
    date_min = df["date"].min()
    date_max = df["date"].max()
    date_range_years = (date_max - date_min).days / 365
    least_date_range = date_range_years >=5.0

    ### Detect Duplicates ##
    duplicate_data = df.duplicated(subset=["date", "market", "commodity"]).sum()

    null_rate = {col: round(df[col].isna().mean() * 100,2) for col in df.columns}

    ## Detect outliers in price ##
    price_stats = df["price"].describe()

    ## Measure the relative stability of the price ##
    price_coefficient_of_variation = (df["price"].std() / df["price"].mean()) * 100

    ## Create Report ###
    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "pipeline_stage": "validate.py",
        "summary": {
            "total_rows": len(df),
            "total_columns": len(df.columns),
            "schema_passed": schema_passed,
            "all_checks_passed": (
                schema_passed
                and len(missing_markets) == 0
                and len(missing_commodities) == 0
                and least_date_range
                #and duplicate_data == 0
            ),
        },
        "schema_validation": {
            "passed": schema_passed,
            "errors": schema_errors,
        },
        "business_rule_checks": {
            "markets_expected": TARGET_MARKETS,
            "present_markets": present_markets,
            "missing_markets": missing_markets,
            "markets_check": len(missing_markets) == 0,
            "commodities_expected": TARGET_COMMODITIES,
            "present_commodities": present_commodities,
            "missing_commodities": missing_commodities,
            "commodities_check": len(missing_commodities) == 0,
            "date_range_earliest": date_min.isoformat(),
            "date_range_latest": date_max.isoformat(),
            "date_range_years": round(date_range_years, 1),
            "date_range_check": least_date_range,
            "duplicate_records": int(duplicate_data),
            "duplicate_check": duplicate_data == 0,

        },
        "null_rates_percent": null_rate,
        "price_statistics": {
            "min": round(price_stats["min"], 2),
            "max": round(price_stats["max"], 2),
            "mean": round(price_stats["mean"], 2),
            "median": round(price_stats["50%"], 2),
            "std": round(price_stats["std"], 2),
            "coefficient_of_variation_pcts": round(price_coefficient_of_variation, 1),

        },
    }

    return report

